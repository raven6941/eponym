## Adequacy contract for elaboration (issue #38).
##
## Twelf's adequacy methodology — an encoding must be a compositional
## bijection between object-language entities and canonical forms — stated
## as a *tested* contract on Eponym's surface→core boundary. A failing
## property points at exactly the phase boundary that broke.
##
## The contract (see docs/adequacy.md):
##   P1 totality:        every well-scoped surface term elaborates.
##   P2 compositionality: elab(lam(x,A,t)).body ≡α elab(t) under the extended
##                        ctx; elab(app(f,x)) ≡α app(elab(f), elab(x));
##                        elab(fst(p)) ≡α fst(elab(p)).
##   P3 substitution:    elab(substPre(t,x,u)) ≡α subst(elab(t), 0, elab(u)).
##   P4 surface round-trip: `$`(t) re-parses and re-elaborates to an α-equal core.
##   P5 injectivity:     distinct numerals elaborate to distinct cores
##                        (the contract's "distinct surfaces → distinct cores",
##                        pinned on the numeral fragment so a degenerate
##                        elaborator cannot pass P1–P4).
##   P7 integer-one:     `1` is the unit type (QTT); the integer literal one
##                        is written `01`; the renderer emits `01` for
##                        pkInt(1) so render->parse is faithful (#158).
##
## α-equality = structural equality on core Terms, ignoring binder *names*
## (de Bruijn indices carry binding) but including impl/erased/quantity
## flags and global refIds.
##
## Terms are generated by a seeded xorshift64* RNG (same pattern as
## tests/fuzz_soundness.nim): deterministic across platforms, so CI runs a
## fixed seed. Fresh-seed runs can be done locally by changing Seed.
##
## Fragment: Nat with zero/suc (as `data`), integer literals (tNatLit),
## explicit lambdas/applications, pairs with fst/snd. All binders are
## explicit with default quantities, so the `$` surface render is faithful
## (the renderer drops quantity annotations; the generator never uses any).

import elab
import preterm
import eponym_init
import parse_surf
import unify
import tables
import strutils

const Seed = 20261013'u64
const N = 300  # cases per property

# --- seeded RNG -------------------------------------------------------------

type Rng = object
  s: uint64

proc initRng(seed: uint64): Rng =
  var s = seed
  if s == 0: s = 0x9E3779B97F4A7C15'u64
  Rng(s: s)

proc next(r: var Rng): uint64 =
  var x = r.s
  x = x xor (x shr 12)
  x = x xor (x shl 25)
  x = x xor (x shr 27)
  r.s = x
  x * 0x2545F4914F6CDD1D'u64

proc below(r: var Rng, n: int): int =
  (r.next() mod n.uint64).int

# --- prelude ----------------------------------------------------------------

let (globals, _, _) = elabPrelude("""
data Nat : ? where
| zero : Nat
| suc (n : Nat) : Nat
""")
let natTm = globals["Nat"].tm
let natV = mkVar("Nat")
let piNatNat = block:
  var ms = initMetaStore(); var supply = Supply()
  zonk(ms, checkTermElab(mkArrow(natV, natV), @[], globals, ms, supply,
                         tmC(cStar)))
let sigNatNat = block:
  var ms = initMetaStore(); var supply = Supply()
  zonk(ms, checkTermElab(mkSigma("s", natV, natV), @[], globals, ms, supply,
                         tmC(cStar)))

proc ctxOf(names: varargs[string]): Ctx =
  for n in names:
    result.add(CtxEntry(name: n, ty: natTm, qty: qOmega))

# --- α-equality on core terms ------------------------------------------------

proc alphaEq(a, b: Term): bool =
  if a.isNil and b.isNil: return true
  if a.isNil or b.isNil: return false
  if a.kind != b.kind: return false
  case a.kind
  of tR: a.refId == b.refId
  of tV: a.idx == b.idx
  of tC: a.c == b.c
  of tType: a.lvl == b.lvl  # Issue #52: level-annotated universes
  of tInt: a.intVal == b.intVal
  of tNatLit: a.natLitVal == b.natLitVal
  of tNatSing: a.natSingVal == b.natSingVal
  of tPrim: a.primOp == b.primOp and alphaEq(a.primTy, b.primTy)
  of tPi, tSi, tLam:
    a.impl == b.impl and a.erased == b.erased and a.qty == b.qty and
      alphaEq(a.dom, b.dom) and alphaEq(a.scope.bdy, b.scope.bdy)
  of tPair:
    alphaEq(a.pFst, b.pFst) and alphaEq(a.pSnd, b.pSnd) and
      alphaEq(a.pScope.bdy, b.pScope.bdy)
  of tApp: alphaEq(a.fn, b.fn) and alphaEq(a.arg, b.arg)
  of tFst: alphaEq(a.sub, b.sub)
  of tSnd: alphaEq(a.sub, b.sub)
  of tAbsurd: alphaEq(a.sub, b.sub)
  of tLet:
    alphaEq(a.letVal, b.letVal) and alphaEq(a.letTy, b.letTy) and
      alphaEq(a.letScope.bdy, b.letScope.bdy)
  of tMeta:
    # Zonked success-path terms must be meta-free; a surviving meta is a
    # contract violation, reported as inequality.
    false

# --- elaboration helpers (fresh state per term, zonked output) ---------------

proc elabC(pre: PreTerm, expTy: Term): Term =
  var ms = initMetaStore(); var supply = Supply()
  zonk(ms, checkTermElab(pre, @[], globals, ms, supply, expTy))

proc elabO(pre: PreTerm, ctx: Ctx, expTy: Term): Term =
  var ms = initMetaStore(); var supply = Supply()
  zonk(ms, checkTermElab(pre, ctx, globals, ms, supply, expTy))

# --- generators: well-scoped PreTerms by construction ------------------------
#
# Mode discipline: integer literals are checking-only constructs (like
# `by` tactics): inferTm's pkInt case requires a postulated `Int`, while
# checkTm's pkInt case overloads against the expected type (Nat here).
# Application infers its function, so anything in function position must
# be literal-free *transitively*. genArr (function-position terms) is
# therefore literal-free; genNat keeps literals for checked positions.

proc genNat(r: var Rng, depth: int, nvars: int, noLit = false): PreTerm
proc genArr(r: var Rng, depth: int, nvars: int): PreTerm
proc genSig(r: var Rng, depth: int, nvars: int, noLit = false): PreTerm =
  mkPair(genNat(r, depth, nvars, noLit), genNat(r, depth, nvars, noLit))

proc sucChain(n: int): PreTerm =
  ## suc applied n times to zero — the literal-free numeral.
  result = mkVar("zero")
  for _ in 1 .. n: result = mkApp(mkVar("suc"), result)

proc genNatLit(r: var Rng, bound: int, noLit: bool): PreTerm =
  let n = r.below(bound)
  if noLit: sucChain(n) else: mkInt(n)

proc genNat(r: var Rng, depth: int, nvars: int, noLit = false): PreTerm =
  ## Well-scoped PreTerm of type Nat; free vars among x0..x(nvars-1).
  ## noLit: avoid integer literals (for terms that will be inferred).
  if depth <= 0:
    if nvars > 0 and r.below(2) == 0: mkVar("x" & $r.below(nvars))
    else: genNatLit(r, 4, noLit)
  else:
    case r.below(7)
    of 0: genNatLit(r, 10, noLit)
    of 1: mkApp(mkVar("suc"), genNat(r, depth - 1, nvars, noLit))
    of 2: mkApp(genArr(r, depth - 1, nvars), genNat(r, depth - 1, nvars, noLit))
    of 3: mkFst(genSig(r, depth - 1, nvars, noLit))
    of 4: mkSnd(genSig(r, depth - 1, nvars, noLit))
    of 5:
      if nvars > 0 and r.below(2) == 0: mkVar("x" & $r.below(nvars))
      else: genNatLit(r, 4, noLit)
    else: mkApp(mkVar("suc"), genNat(r, depth - 1, nvars, noLit))

proc genArr(r: var Rng, depth: int, nvars: int): PreTerm =
  ## Well-scoped PreTerm of type Nat -> Nat for *function position*
  ## (application infers the function): literal-free, transitively.
  if depth <= 0 or r.below(3) == 0: mkVar("suc")
  else: mkLam("x" & $nvars, natV, genNat(r, depth - 1, nvars + 1, noLit = true))

# --- property driver --------------------------------------------------------

var failures = 0

template checkProp(cond: bool, msg: string) =
  if not cond:
    inc failures
    echo "FAIL: ", msg

template elabOk(msg: string, body: untyped) =
  # Note: `except ElabError as e` breaks parsing of the command-syntax call
  # below (Nim quirk), so the message comes from getCurrentExceptionMsg().
  try: body
  except ElabError:
    checkProp(false, msg & " — ElabError: " & getCurrentExceptionMsg())

let ctx2 = ctxOf("x0", "x1")   # innermost-first: x0 = V0, x1 = V1
let ctx1 = ctxOf("x1")         # x1 = V0

# P1: totality — every well-scoped surface term elaborates.
block:
  var r = initRng(Seed)
  for i in 0 ..< N:
    let t = genNat(r, 4, 0)
    elabOk "P1 closed term " & $i & ": " & $t:
      discard elabC(t, natTm)
  for i in 0 ..< N:
    let t = genNat(r, 4, 2)
    elabOk "P1 open term " & $i & ": " & $t:
      discard elabO(t, ctx2, natTm)
  echo "ok: P1 totality (", 2 * N, " terms elaborated)"

# P2a: compositionality — lambda body.
block:
  var r = initRng(Seed + 1)
  for i in 0 ..< N:
    let t = genNat(r, 3, 2)
    let lam = mkLam("x2", natV, t)
    elabOk "P2a case " & $i & ": " & $lam:
      let core1 = elabO(lam, ctx2, piNatNat)
      let core2 = elabO(t, ctxOf("x2", "x0", "x1"), natTm)
      checkProp(core1.kind == tLam, "P2a case " & $i & ": not a tLam")
      checkProp(alphaEq(core1.scope.bdy, core2),
                "P2a case " & $i & ": lam body differs from elab of body")
      checkProp(alphaEq(core1.dom, natTm),
                "P2a case " & $i & ": lam domain differs from Nat")
  echo "ok: P2a lambda compositionality"

# P2b: compositionality — application.
block:
  var r = initRng(Seed + 2)
  for i in 0 ..< N:
    let f = genArr(r, 3, 0)
    let x = genNat(r, 3, 0)
    elabOk "P2b case " & $i:
      let coreF = elabC(f, piNatNat)
      let coreX = elabC(x, natTm)
      let core1 = elabC(mkApp(f, x), natTm)
      checkProp(alphaEq(core1, tmApp(coreF, coreX)),
                "P2b case " & $i & ": elab(app) differs from app(elab, elab)")
  echo "ok: P2b application compositionality"

# P2c: compositionality — fst projection.
block:
  var r = initRng(Seed + 3)
  for i in 0 ..< N:
    let p = genSig(r, 3, 0)
    elabOk "P2c case " & $i:
      let coreP = elabC(p, sigNatNat)
      let core1 = elabC(mkFst(p), natTm)
      checkProp(alphaEq(core1, tmFst(coreP)),
                "P2c case " & $i & ": elab(fst p) differs from fst(elab p)")
  echo "ok: P2c fst compositionality"

# P3: substitution commutation.
block:
  var r = initRng(Seed + 4)
  for i in 0 ..< N:
    let t = genNat(r, 3, 2)   # open over x0, x1
    # u is literal-free: substitution must not introduce a literal into
    # an inferred position (e.g. the body of an applied lambda) — the
    # same mode discipline as the generator (see P6).
    let u = genNat(r, 3, 0, noLit = true)   # closed
    elabOk "P3 case " & $i & ": t=" & $t & " u=" & $u:
      let coreT = elabO(t, ctx2, natTm)   # x0 = V0, x1 = V1
      let coreU = elabC(u, natTm)
      var fresh = 1000
      let tSub = substPre(t, "x0", u, fresh)
      let left = elabO(tSub, ctx1, natTm)  # x1 = V0
      let right = subst(coreT, 0, coreU)
      checkProp(alphaEq(left, right),
                "P3 case " & $i & ": elab(subst) differs from subst(elab)")
  echo "ok: P3 substitution commutation"

proc hasIntOne(p: PreTerm): bool =
  ## True if p contains the integer literal 1. Retained as documentation of
  ## the surface contract (issue #158): `1` lexes as the unit *type* (QTT),
  ## so the integer literal one is written `01` and the renderer emits `01`
  ## for pkInt(1) — render->parse is faithful and P4 needs no skip.
  if p.isNil: return false
  (p.kind == pkInt and p.intVal == 1) or
    hasIntOne(p.c1) or hasIntOne(p.c2) or hasIntOne(p.c3)

# P4: surface round-trip — `$`(t) re-parses and re-elaborates to an α-equal core.
# (Issue #158: pkInt(1) renders as `01`, which re-parses to pkInt(1); the
# former pkInt(1) skip is gone.)
block:
  var r = initRng(Seed + 5)
  var ran = 0
  var withOne = 0  # terms containing pkInt(1): the #158 case must be exercised
  for i in 0 ..< N:
    let t = genNat(r, 4, 0)
    inc ran
    if hasIntOne(t): inc withOne
    let src = "proc tmp : Nat =\n  " & $t & "\n"
    elabOk "P4 case " & $i & ": " & $t:
      let decls = parseProgram(src)
      checkProp(decls.len == 1 and decls[0].kind == dkDef,
                "P4 case " & $i & ": re-parse did not yield one def")
      let body = decls[0].def.body
      checkProp(body == t, "P4 case " & $i & ": re-parsed preterm differs")
      let core1 = elabC(body, natTm)
      let core2 = elabC(t, natTm)
      checkProp(alphaEq(core1, core2),
                "P4 case " & $i & ": re-elaborated core differs")
  checkProp(withOne > 0, "P4: no generated term contained pkInt(1); #158 case untested")
  echo "ok: P4 surface round-trip (", ran, " cases, ", withOne,
       " with pkInt(1) via `01`, issue #158)"

# P5: injectivity on numerals — distinct surfaces, distinct cores.
block:
  var cores: seq[Term] = @[]
  for i in 0 .. 9:
    elabOk "P5 numeral " & $i:
      cores.add(elabC(mkInt(i), natTm))
  for i in 0 .. 9:
    for j in 0 .. 9:
      if i != j:
        checkProp(not alphaEq(cores[i], cores[j]),
                  "P5: numerals " & $i & " and " & $j & " are α-equal")
  echo "ok: P5 numeral injectivity"

# P6: intentional partiality — literals need an expected type.
#
# Integer literals are checking-only (like `by` tactics): a literal in
# inference position is *rejected* ("integer literal requires ..."), not
# silently defaulted. This pins the intended partiality so a future
# change that defaults literals in inference mode trips the suite.
block:
  var r = initRng(Seed + 6)
  var rejected = 0
  for i in 0 ..< 100:
    # Literal in a lambda body; the lambda is applied, so the body is
    # inferred and the literal has no expected type.
    let f = mkLam("x9", natV, mkInt(r.below(10)))
    let x = genNatLit(r, 5, noLit = false)
    var ms = initMetaStore(); var supply = Supply()
    try:
      discard checkTermElab(mkApp(f, x), @[], globals, ms, supply, natTm)
      checkProp(false, "P6 case " & $i & ": literal in inference position " &
                "elaborated (expected rejection)")
    except ElabError as e:
      if "integer literal requires" in e.msg: inc rejected
      else: checkProp(false, "P6 case " & $i & ": wrong error: " & e.msg)
  checkProp(rejected == 100, "P6: only " & $rejected & "/100 rejected")
  echo "ok: P6 literal inference partiality (", rejected, "/100 rejected)"

# P7: integer-one surface contract (issue #158).
#
# `1` is the unit *type* (QTT); the integer literal one is written `01`.
# The renderer must emit `01` for pkInt(1) so render->parse is faithful.
block:
  checkProp($mkInt(1) == "01", "P7: $pkInt(1) is \"" & $mkInt(1) & "\", want \"01\"")
  checkProp($mkInt(2) == "2", "P7: $pkInt(2) is \"" & $mkInt(2) & "\", want \"2\"")
  checkProp($mkUnitTy() == "1", "P7: $pkUnitTy is \"" & $mkUnitTy() & "\", want \"1\"")
  elabOk "P7 parse `01`":
    let decls = parseProgram("proc tmp : Nat =\n  01\n")
    checkProp(decls.len == 1 and decls[0].kind == dkDef,
              "P7: `01` did not parse to one def")
    checkProp(decls[0].def.body == mkInt(1),
              "P7: `01` parsed to " & $decls[0].def.body & ", want pkInt(1)")
  elabOk "P7 parse `1` as unit type":
    let decls = parseProgram("proc tmp : ? =\n  1\n")
    checkProp(decls.len == 1 and decls[0].kind == dkDef,
              "P7: `1` did not parse to one def")
    checkProp(decls[0].def.body.kind == pkUnitTy,
              "P7: `1` parsed to kind " & $decls[0].def.body.kind & ", want pkUnitTy")
  echo "ok: P7 integer-one surface contract (issue #158)"

if failures > 0:
  echo failures, " adequacy property failures"
  quit(1)
echo "all adequacy properties passed"
