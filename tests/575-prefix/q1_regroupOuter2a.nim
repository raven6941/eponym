                outer(n,resid(n,H,s2,y2),matVec(n,W,y2))),
              scalMat(n,divF(dot(n,resid(n,H,s1,y1),y2),
                mulF(dot(n,matVec(n,W,y1),y1),dot(n,matVec(n,W,y2),y2))),
                outer(n,matVec(n,W,y1),matVec(n,W,y2)))),
