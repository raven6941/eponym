                outer(n,matVec(n,W,y2),matVec(n,W,y1))))),
          scalMat(n,divF(dot(n,y2,resid(n,H,s2,y2)),
            mulF(dot(n,matVec(n,W,y2),y2),dot(n,matVec(n,W,y2),y2))),
            outer(n,matVec(n,W,y2),matVec(n,W,y2)))),
        matSub(n,matSub(n,
          scalMat(n,recipF(dot(n,y2,matVec(n,W,y2))),
            matAdd(n,outer(n,resid(n,H,s2,y2),matVec(n,W,y2)),
              outer(n,matVec(n,W,y2),resid(n,H,s2,y2)))),
