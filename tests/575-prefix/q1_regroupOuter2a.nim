        single1(n,H,W,s1,y1,s2,y2)),
      cong[Mat[n,n],Mat[n,n]](lam(t: Mat[n,n]) => matAdd(n,H,matSub(n,
          scalMat(n,recipF(dot(n,y1,matVec(n,W,y1))),
