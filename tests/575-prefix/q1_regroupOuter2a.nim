  proc regroupX(n: Nat, H: Mat[n,n], W: Mat[n,n], s1: Vec[Float,n], y1: Vec[Float,n],
      s2: Vec[Float,n], y2: Vec[Float,n]):
      Eq[Mat[n,n],
        matAdd(n,H,matSub(n,
          matAdd(n,term1(n,H,W,s1,y1),term2(n,H,W,s1,y1)),term3(n,H,W,s1,y1))),
        matAdd(n,H,matSub(n,
          scalMat(n,recipF(dot(n,y1,matVec(n,W,y1))),
            matAdd(n,outer(n,resid(n,H,s1,y1),matVec(n,W,y1)),
              outer(n,matVec(n,W,y1),resid(n,H,s1,y1)))),
          scalMat(n,divF(dot(n,resid(n,H,s1,y1),y1),
            mulF(dot(n,y1,matVec(n,W,y1)),dot(n,y1,matVec(n,W,y1)))),
            outer(n,matVec(n,W,y1),matVec(n,W,y1)))))] =
    calc2[Mat[n,n]](
      matAdd(n,H,matSub(n,
        matAdd(n,term1(n,H,W,s1,y1),term2(n,H,W,s1,y1)),term3(n,H,W,s1,y1))),
      matAdd(n,H,matSub(n,
        scalMat(n,recipF(dot(n,y1,matVec(n,W,y1))),
