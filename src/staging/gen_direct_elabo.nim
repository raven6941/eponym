## Direct-style code generator for #57 — run at build time, emits Nim source.
##
## Usage: nim c -r --path:src src/staging/gen_direct_elabo.nim -- 8 > src/staging/gen_elabo_vec.nim
##
## Generates specialized direct-style elaborators for Vec(Nat, N):
##   proc elaboVecN(tm: RTerm): Option[RTerm]
## No Goal/Stream machinery, no unification — just pattern matching and
## recursion. This is the "complete staging" #26 lacked.

import os
import strutils
import minikanren
import rel_elab_dep
import rel_elab_out

proc genVecElabo(n: int): string =
  ## Generate the Nim source for elaboVecN (tm : Vec(Nat, N)).
  result = ""
  let pname = "elaboVec" & $n
  result &= "proc " & pname & "*(tm: RTerm): Option[RTerm] =\n"
  result &= "  ## Direct-style elaborator for Vec(Nat, " & $n & "), generated by gen_direct_elabo.\n"
  result &= "  ## tm is the surface RTerm; returns Some(core) or None.\n"
  if n == 0:
    # Vec(Nat, 0): only nil, reify Nat as element type
    result &= "  if tm.kind == rkAtom and tm.name == \"nil\":\n"
    result &= "    some(nilCore(natTy()))\n"
    result &= "  else:\n"
    result &= "    none(RTerm)\n"
  else:
    # Vec(Nat, n): cons(h, t) where h:Nat, t:Vec(Nat, n-1)
    let sub = "elaboVec" & $(n-1)
    let nPrevCore = if n-1 == 0: "zeroTm()"
                    else: "sucCore(" & "zeroTm()".repeat(1) & ")"  # placeholder
    # Build the index core term: suc applied (n-1) times to zero
    var idxCore = "zeroTm()"
    for i in 1 ..< n:
      idxCore = "sucCore(" & idxCore & ")"
    result &= "  if tm.kind == rkPair and tm.head.kind == rkAtom and tm.head.name == \"cons\":\n"
    result &= "    let h = tm.tail.head\n"
    result &= "    let t = tm.tail.tail.head\n"
    result &= "    let hE = elaboNat(h)\n"
    result &= "    if hE.isNone: return none(RTerm)\n"
    result &= "    let tE = " & sub & "(t)\n"
    result &= "    if tE.isNone: return none(RTerm)\n"
    result &= "    some(consCore(natTy(), " & idxCore & ", hE.get, tE.get))\n"
    result &= "  else:\n"
    result &= "    none(RTerm)\n"

when isMainModule:
  var argIdx = 1
  if paramCount() >= 1 and paramStr(1) == "--": inc argIdx  # skip separator
  let n = if paramCount() >= argIdx: parseInt(paramStr(argIdx)) else: 2
  echo "import options"
  echo "import minikanren"
  echo "import rel_elab_dep"
  echo "import rel_elab_out"
  echo ""
  echo "## Generated by gen_direct_elabo.nim — DO NOT EDIT"
  echo "## Direct-style elaborators for Vec(Nat, 0).." & $n
  echo ""
  # elaboNat is hand-written (small, not generated)
  echo "proc elaboNat*(tm: RTerm): Option[RTerm] ="
  echo "  if tm.kind == rkAtom and tm.name == \"zero\":"
  echo "    some(zeroTm())"
  echo "  elif tm.kind == rkPair and tm.head.kind == rkAtom and tm.head.name == \"suc\":"
  echo "    let nE = elaboNat(tm.tail.head)"
  echo "    if nE.isSome: some(sucCore(nE.get))"
  echo "    else: none(RTerm)"
  echo "  else:"
  echo "    none(RTerm)"
  echo ""
  for i in 0 .. n:
    echo genVecElabo(i)
    echo ""
